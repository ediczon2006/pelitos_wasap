def exportar():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.makedirs(os.path.join(base_dir, "data"), exist_ok=True)
    os.makedirs(os.path.join(base_dir, "02_matriz_maestra"), exist_ok=True)

    # Exportar CSV
    csv_path = os.path.join(base_dir, "02_matriz_maestra", "matriz_maestra_catalogos.csv")
    fieldnames = list(CATALOGO[0].keys())
    with open(csv_path, mode="w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(CATALOGO)
    print(f"Exportado CSV: {csv_path}")

    # Exportar JSON
    json_path = os.path.join(base_dir, "data", "catalogo_maestro.json")
    with open(json_path, mode="w", encoding="utf-8") as f:
        json.dump(CATALOGO, f, indent=2, ensure_ascii=False)
    print(f"Exportado JSON: {json_path}")

if __name__ == "__main__":
    exportar()
